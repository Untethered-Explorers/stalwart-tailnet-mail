#!/usr/bin/env bash
#
# 32-agent-app-password.sh — create the agent app password via admin JMAP.
# Run as root, in recovery mode.
#
# Separate from 30-configure.sh so it can be re-run on its own when the CLI's
# account query misbehaves. Idempotent: it skips when the credentials file
# already records an app password.

set -euo pipefail

HERE="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
URL="http://127.0.0.1:8080"
PW_FILE=/root/stalwart-recovery-password
CRED_FILE=/root/mail-credentials.txt
AGENT_USER="${AGENT_USER:-agent-bot}"

log()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
info() { printf '    %s\n' "$*"; }
die()  { printf '\033[1;31m[error]\033[0m %s\n' "$*" >&2; exit 1; }

[[ ${EUID} -eq 0 ]] || die "run with sudo: sudo bash $0"
[[ -s $PW_FILE ]] || die "$PW_FILE is missing"
RECOVERY_PW="$(cat "$PW_FILE")"

jmap() {
    curl -fsS -u "admin:$RECOVERY_PW" \
        -H 'Content-Type: application/json' -d "$1" "$URL/jmap/"
}

log "Looking up $AGENT_USER"
ACCOUNTS="$(jmap '{"using":["urn:ietf:params:jmap:core","urn:stalwart:jmap"],
    "methodCalls":[["x:Account/get",{"ids":null},"0"]]}')" \
    || die "x:Account/get failed"

printf '%s\n' "$ACCOUNTS" | jq -r '.methodResponses[0][1].list[]? | "    \(.id)  \(.name)  \(.emailAddress // "")"'

AGENT_ID="$(printf '%s' "$ACCOUNTS" | jq -r --arg n "$AGENT_USER" \
    '.methodResponses[0][1].list | map(select(.name==$n))[0].id // empty')"
[[ -n $AGENT_ID ]] || die "$AGENT_USER not found in the account list"
info "account id: $AGENT_ID"

if grep -q 'app-password' "$CRED_FILE" 2>/dev/null; then
    info "an app password is already recorded in $CRED_FILE — nothing to do"
    exit 0
fi

log "Creating the app password"
PAYLOAD="$(jq -n --arg id "$AGENT_ID" --arg desc "$AGENT_USER-opencode" '{
    using: ["urn:ietf:params:jmap:core", "urn:stalwart:jmap"],
    methodCalls: [[ "x:AppPassword/set", {
        accountId: $id,
        create: { p1: {
            description: $desc,
            permissions: { "@type": "Inherit" },
            allowedIps: {}
        } }
    }, "0" ]]
}')"

RESPONSE="$(jmap "$PAYLOAD")" || die "x:AppPassword/set failed"
SECRET="$(printf '%s' "$RESPONSE" | jq -r '.methodResponses[0][1].created.p1.secret // empty')"
if [[ -z $SECRET ]]; then
    printf '%s\n' "$RESPONSE" >&2
    die "could not parse the app-password secret"
fi

if [[ ! -s $CRED_FILE ]]; then
    ( umask 077
      printf '# Generated by migrate/32-agent-app-password.sh\n' > "$CRED_FILE"
      printf 'webmail = https://mcsquirrel.tailc7d454.ts.net/webmail/\n' >> "$CRED_FILE"
    )
fi
( umask 077
  printf '%-15s = %s   (use this in agent configs)\n' "app-password" "$SECRET" >> "$CRED_FILE"
)
chmod 0600 "$CRED_FILE"

info "app password created and appended to $CRED_FILE"
